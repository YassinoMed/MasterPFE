        </header>
        
        <div class=\"dashboard\">
            <div class=\"card\">
                <div class=\"card-title\">Compliance Score</div>
                <div class=\"card-value\" style=\"color: {score_color}\">{compliance_score}%</div>
                <div class=\"score-gauge\">
                    <div class=\"score-fill\" style=\"width: {compliance_score}%\"></div>
                </div>
            </div>
            <div class=\"card\">
                <div class=\"card-title\">Pods Analysés</div>
                <div class=\"card-value\">{total_pods}</div>
