#!/usr/bin/env bash
# security/tests/kyverno-audit-report.sh
# Performs a Kyverno Enforce dry-run audit against active pods and generates an HTML report.

set -euo pipefail

KYVERNO_VERSION="v1.12.5"
POLICY_DIR="k8s/kyverno-policies/enforce"
AUDIT_DIR="/tmp/kyverno-audit"
REPORT_HTML="security/reports/kyverno-audit-report.html"

echo "=== KYVERNO ENFORCE DRY-RUN AUDIT ==="

# 1. Ensure Kyverno CLI is installed
if ! command -v kyverno &> /dev/null; then
    echo "[INFO] Kyverno CLI not found. Downloading version ${KYVERNO_VERSION}..."
    curl -Lo /tmp/kyverno.tar.gz "https://github.com/kyverno/kyverno/releases/download/${KYVERNO_VERSION}/kyverno-cli_${KYVERNO_VERSION}_linux_x86_64.tar.gz"
    tar -xzf /tmp/kyverno.tar.gz -C /tmp
    mv /tmp/kyverno /usr/local/bin/kyverno
    chmod +x /usr/local/bin/kyverno
    rm -f /tmp/kyverno.tar.gz
    echo "[OK] Kyverno CLI installed successfully."
else
    echo "[OK] Kyverno CLI is already installed: $(kyverno version | grep Version || true)"
fi

# 2. Extract manifests from the cluster
echo "[INFO] Extracting active pods from cluster (namespaces: securerag-hub, recette)..."
rm -rf "$AUDIT_DIR"
mkdir -p "$AUDIT_DIR"

kubectl get pods -n securerag-hub -o yaml > "$AUDIT_DIR/securerag-hub-pods.yaml" 2>/dev/null || echo "---" > "$AUDIT_DIR/securerag-hub-pods.yaml"
kubectl get pods -n recette -o yaml > "$AUDIT_DIR/recette-pods.yaml" 2>/dev/null || echo "---" > "$AUDIT_DIR/recette-pods.yaml"

# Remove status and metadata fields that are not relevant to validation to clean up the dry-run
# (Kyverno CLI can handle them, but cleaning metadata avoids clutter)
python3 -c "
import yaml, sys, os
for f in os.listdir('$AUDIT_DIR'):
    if not f.endswith('.yaml'): continue
    path = os.path.join('$AUDIT_DIR', f)
    try:
        with open(path, 'r') as file:
            content = yaml.safe_load(file)
        os.remove(path)
        if content and 'items' in content:
            for idx, item in enumerate(content['items']):
                if 'status' in item: del item['status']
                if 'metadata' in item:
                    meta = item['metadata']
                    for key in ['uid', 'resourceVersion', 'creationTimestamp', 'managedFields', 'ownerReferences']:
                        if key in meta: del meta[key]
                new_path = os.path.join('$AUDIT_DIR', f'pod-{f}-{idx}.yaml')
                with open(new_path, 'w') as new_file:
                    yaml.safe_dump(item, new_file)
    except Exception as e:
        print(f'Warning cleaning/unpacking {f}: {e}')
"

# 3. Simulate Enforce mode via dry-run using Kyverno CLI
echo "[INFO] Running Kyverno CLI apply and generating policy report..."
# Use wildcard to load all policies to bypass directory load limitations in some CLI versions
kyverno apply "$POLICY_DIR"/*.yaml --resource "$AUDIT_DIR" --policy-report > "$AUDIT_DIR/report.yaml" 2>/dev/null || true

# 4. Process report and generate HTML using Python
echo "[INFO] Compiling results and generating HTML report..."
mkdir -p "$(dirname "$REPORT_HTML")"

python3 -c "
