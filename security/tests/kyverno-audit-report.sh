import sys
import os
import datetime

report_path = '$AUDIT_DIR/report.yaml'
html_path = '$REPORT_HTML'

if not os.path.exists(report_path):
    print('[ERROR] Policy report not generated by Kyverno CLI.')
    sys.exit(1)

with open(report_path, 'r') as f:
    report = yaml.safe_load(f)

if not report:
    report = {}

results = report.get('results', [])
summary = report.get('summary', {'pass': 0, 'fail': 0, 'warn': 0, 'error': 0, 'skip': 0})

all_pods = set()
failed_pods = set()
violations = []

for res in results:
    status = res.get('result')
    policy = res.get('policy')
    rule = res.get('rule')
    message = res.get('message')
    
    resources = res.get('resources', [])
    if not resources:
        continue
    resource = resources[0]
    kind = resource.get('kind')
    name = resource.get('name')
    namespace = resource.get('namespace', 'default')
    
    if kind != 'Pod':
        continue
        
    pod_id = f'{namespace}/{name}'
    all_pods.add(pod_id)
    
    if status == 'fail':
        failed_pods.add(pod_id)
        violations.append({
            'namespace': namespace,
            'pod': name,
            'policy': policy,
            'rule': rule,
            'message': message
        })

total_pods = len(all_pods)
failed_pods_count = len(failed_pods)
compliant_pods_count = total_pods - failed_pods_count

if total_pods > 0:
    compliance_score = (compliant_pods_count * 100) // total_pods
else:
    compliance_score = 100

date_str = datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')

score_color = 'var(--color-pass)'
if compliance_score < 50:
    score_color = 'var(--color-fail)'
elif compliance_score < 80:
    score_color = 'var(--color-warn)'

fail_color_style = 'color: var(--color-fail)' if failed_pods_count > 0 else 'color: var(--text-primary)'

table_body = ''
if violations:
    table_body = '<table><thead><tr><th>Namespace</th><th>Pod</th><th>Politique</th><th>Règle</th><th>Message d\\'erreur</th></tr></thead><tbody>'
    for v in violations:
        table_body += f'''<tr>
            <td><code>{v['namespace']}</code></td>
            <td><strong>{v['pod']}</strong></td>
            <td><code>{v['policy']}</code></td>
            <td><code>{v['rule']}</code></td>
            <td><span class=\"status-fail\">{v['message']}</span></td>
        </tr>'''
    table_body += '</tbody></table>'
else:
    table_body = '<div style=\"padding: 2rem; text-align: center; color: var(--text-secondary);\">Aucune violation détectée ! Tous les pods sont conformes.</div>'

html_content = f'''<!DOCTYPE html>
<html lang=\"fr\">
<head>
    <meta charset=\"UTF-8\">
    <meta name=\"viewport\" content=\"width=device-width, initial-scale=1.0\">
